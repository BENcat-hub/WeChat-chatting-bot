"""Measure identity fidelity between a character reference image and generated images.

The six-axis scorer in `eval_vl_score.py` answers "is this a good picture"; it cannot
answer "is this the same character as the reference" — which is the question that
decides whether a reference image is actually being used (or ignored) by the upstream
model. This script pairs each generated image with the reference and lets a free VL
model judge identity consistency, then aggregates numbers per set.

Example:
  python scripts/eval_vl_identity.py --ref persona.png \
      --set "crop563=logs/jimeng-out/eval/ref-1024x1024-r1-a.png,logs/jimeng-out/eval/ref-1024x1024-r2-a.png" \
      --set "fullbody=logs/jimeng-out/eval/ref-1024x1024-r1-b.png"
"""

from __future__ import annotations

import argparse
import json
import random
import re
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import free_llm  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
VL_MODEL = "nvidia/nemotron-3.5-super-vl:free"
LOG = ROOT / "logs" / "image-eval-identity.jsonl"

try:  # Windows consoles default to GBK and crash on non-ASCII model output
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
except Exception:  # noqa: BLE001
    pass

PROMPT = (
    "Image 1 is a character reference sheet. Image 2 is a picture generated by an image model.\n"
    "Judge ONLY how well image 2 preserves the character identity of image 1: face shape, hair colour and\n"
    "hairstyle, eye colour, outfit, and any distinctive feature (for example whale-fin shaped ears or a tail).\n"
    "Ignore pose, camera angle, background, lighting and overall art quality.\n"
    "identity: 1-10, where 10 = clearly the same character with the same face/hair/outfit, and 1 = a different-looking person.\n"
    "same_character: true when a viewer would say it is the same character, even if stylised.\n"
    "used_reference: true when image 2 shows evidence of having been conditioned on image 1 rather than generated freely.\n"
    'Reply with JSON only, no prose: {"identity":n,"same_character":true|false,"used_reference":true|false,"notes":"..."}'
)

FIELDS = ("identity", "same_character", "used_reference")


def parse_json(text: str) -> dict:
    match = re.search(r"\{.*\}", text or "", re.S)
    if not match:
        return {}
    try:
        return json.loads(match.group(0))
    except Exception:  # noqa: BLE001
        return {}


def resolve(raw: str) -> Path:
    path = Path(raw.strip())
    return path if path.is_absolute() else (ROOT / path).resolve()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", required=True, help="reference image path")
    ap.add_argument("--set", action="append", default=[], help="name=path1,path2,...")
    ap.add_argument("--tag", default="identity")
    ap.add_argument("--seed", type=int, default=11)
    ap.add_argument("--timeout", type=int, default=240)
    args = ap.parse_args()
    if not args.set:
        raise SystemExit("--set name=path1,path2 is required")

    ref = resolve(args.ref)
    if not ref.exists():
        raise SystemExit(f"reference not found: {ref}")

    items: list[tuple[str, Path]] = []
    for spec in args.set:
        name, _, paths = spec.partition("=")
        for raw in paths.split(","):
            if raw.strip():
                items.append((name.strip(), resolve(raw)))
    random.Random(args.seed).shuffle(items)
    labels = [chr(ord("A") + i) for i in range(len(items))]
    print(f"ref={ref.name} n={len(items)} (order shuffled)")
    print("blind mapping: " + ", ".join(f"{lab}={p.name}({arm})" for lab, (arm, p) in zip(labels, items)))

    per_set: dict[str, list[dict]] = {}
    for lab, (arm, path) in zip(labels, items):
        if not path.exists():
            print(f"{lab} {arm} {path.name}: MISSING")
            continue
        started = time.time()
        try:
            text = free_llm.call(
                VL_MODEL, PROMPT, [str(ref), str(path)], temperature=0.0, max_tokens=2000, timeout=args.timeout
            )
        except SystemExit as exc:
            print(f"{lab} {arm} {path.name}: ERROR {exc}")
            continue
        data = parse_json(text)
        row = {
            "ts": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
            "tag": args.tag,
            "label": lab,
            "arm": arm,
            "file": path.name,
            "ref": ref.name,
            "elapsed": round(time.time() - started, 1),
        }
        if not data:
            row["raw"] = (text or "")[-400:]
        for field in FIELDS:
            row[field] = data.get(field)
        row["notes"] = data.get("notes")
        LOG.parent.mkdir(parents=True, exist_ok=True)
        with LOG.open("a", encoding="utf-8") as fh:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")
        print(
            f"{lab} {arm} {path.name}: identity={row['identity']} same={row['same_character']} "
            f"used_ref={row['used_reference']} notes={row['notes']}"
        )
        per_set.setdefault(arm, []).append(row)

    print("\n=== identity means ===")
    for arm, rows in per_set.items():
        vals = [r["identity"] for r in rows if isinstance(r["identity"], (int, float))]
        same = [r["same_character"] for r in rows if isinstance(r["same_character"], bool)]
        used = [r["used_reference"] for r in rows if isinstance(r["used_reference"], bool)]
        mean = round(sum(vals) / len(vals), 2) if vals else None
        same_rate = f"{sum(same)}/{len(same)}" if same else "n/a"
        used_rate = f"{sum(used)}/{len(used)}" if used else "n/a"
        print(f"{arm}: n={len(rows)} identity_mean={mean} same_character={same_rate} used_reference={used_rate}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
